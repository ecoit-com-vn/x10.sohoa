-- Consolidated Digitization Service Schema

CREATE TABLE FILE_ATTACHMENT (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILE_NAME     VARCHAR2(500)  NOT NULL,
    FILE_PATH     VARCHAR2(2000) NOT NULL,
    CONTENT_TYPE  VARCHAR2(100)  NOT NULL,
    FILE_SIZE     NUMBER         NOT NULL,
    UPLOADED_AT   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPLOADED_BY   VARCHAR2(255)  NOT NULL,
    STATUS        VARCHAR2(50)   DEFAULT 'Uploaded' NOT NULL
);

CREATE TABLE DIGITIZATION_TASK (
    ID                    VARCHAR2(36)   NOT NULL PRIMARY KEY,
    DOSSIER_ID            VARCHAR2(50)   NOT NULL,
    WORKFLOW_STEP_ID      VARCHAR2(36)   NOT NULL,
    ASSIGNED_TO_USER_ID   VARCHAR2(50)   NOT NULL,
    STATUS                VARCHAR2(50)   NOT NULL,
    CREATED_AT            TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT          TIMESTAMP      NULL,
    NOTES                 VARCHAR2(2000) NULL
);

CREATE TABLE OCR_TRAINING_DATA (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILE_NAME           VARCHAR2(500)  NOT NULL,
    FILE_PATH           VARCHAR2(2000) NOT NULL,
    BUCKET_NAME         VARCHAR2(255)  NOT NULL,
    CONTENT_TYPE        VARCHAR2(100)  NOT NULL,
    FILE_SIZE           NUMBER         NOT NULL,
    DOCUMENT_TYPE       VARCHAR2(100),
    LABEL_TEXT          CLOB,
    QUALITY_SCORE       NUMBER(5,2),
    TRAINING_STATUS     VARCHAR2(50)   DEFAULT 'Pending' NOT NULL,
    IS_VERIFIED         NUMBER(1)      DEFAULT 0,
    VERIFIED_BY         VARCHAR2(255),
    VERIFIED_AT         TIMESTAMP,
    NOTES               VARCHAR2(2000),
    UPLOADED_AT         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPLOADED_BY         VARCHAR2(255)  NOT NULL,
    CREATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE VIRTUAL_FOLDERS (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(255) NOT NULL,
    ParentId NUMBER NULL,
    UnitId NUMBER NULL,
    EquipmentId VARCHAR2(36) NULL,
    CreatedBy VARCHAR2(100) NULL,
    CreatedDate TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_virtual_folder_parent FOREIGN KEY (ParentId) REFERENCES VIRTUAL_FOLDERS(Id) ON DELETE CASCADE
);

CREATE TABLE FOLDER_DOCUMENTS (
    FolderId NUMBER NOT NULL,
    DocumentId NUMBER NOT NULL,
    PRIMARY KEY (FolderId, DocumentId),
    CONSTRAINT fk_folder_doc_folder FOREIGN KEY (FolderId) REFERENCES VIRTUAL_FOLDERS(Id) ON DELETE CASCADE,
    CONSTRAINT fk_folder_doc_doc FOREIGN KEY (DocumentId) REFERENCES FILE_ATTACHMENT(ID) ON DELETE CASCADE
);
