-- Consolidated Report Service Schema

CREATE TABLE REPORT_GROUPS (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(255) NOT NULL,
    SortOrder NUMBER DEFAULT 0,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50)
);

CREATE TABLE DYNAMIC_REPORTS (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GroupId NUMBER NOT NULL,
    Name VARCHAR2(255) NOT NULL,
    SqlQuery CLOB NOT NULL,
    ParametersJson CLOB NULL,
    AllowedRoles VARCHAR2(1000) NULL,
    IsActive NUMBER(1) DEFAULT 1,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50),
    CONSTRAINT fk_dynreport_group FOREIGN KEY (GroupId) REFERENCES REPORT_GROUPS(Id) ON DELETE CASCADE
);
