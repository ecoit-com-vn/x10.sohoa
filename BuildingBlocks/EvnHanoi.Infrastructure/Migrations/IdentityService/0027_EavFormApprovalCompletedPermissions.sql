DELETE FROM ROLE_PERMISSION 
WHERE PermissionId = (SELECT Id FROM PERMISSION WHERE Code = 'EAV_FORM_TEMPLATE_APPROVAL_VIEW' AND ROWNUM = 1)
  AND RoleId IN (
      SELECT RoleId FROM ROLE_PERMISSION 
      WHERE PermissionId = (SELECT Id FROM PERMISSION WHERE Code = 'EAV_FORM_APPROVAL_VIEW' AND ROWNUM = 1)
  );

