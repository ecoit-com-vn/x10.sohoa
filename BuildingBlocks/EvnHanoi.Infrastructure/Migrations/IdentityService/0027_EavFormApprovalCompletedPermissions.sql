SET PermissionId = (SELECT Id FROM PERMISSION WHERE Code = 'EAV_FORM_APPROVAL_VIEW' AND ROWNUM = 1)
WHERE PermissionId = (SELECT Id FROM PERMISSION WHERE Code = 'EAV_FORM_TEMPLATE_APPROVAL_VIEW' AND ROWNUM = 1)
  AND (SELECT Id FROM PERMISSION WHERE Code = 'EAV_FORM_APPROVAL_VIEW' AND ROWNUM = 1) IS NOT NULL;

