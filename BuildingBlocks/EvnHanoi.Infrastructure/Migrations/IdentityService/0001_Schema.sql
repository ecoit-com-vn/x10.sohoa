-- Consolidated Identity Service Schema

CREATE TABLE ORGANIZATION_UNIT (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code VARCHAR2(50) NOT NULL,
    Name VARCHAR2(255) NOT NULL,
    ParentId NUMBER NULL,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50)
);

CREATE TABLE APP_USER (
    Id VARCHAR2(36) PRIMARY KEY,
    UserName VARCHAR2(50) NOT NULL UNIQUE,
    Email VARCHAR2(100) NULL,
    FullName VARCHAR2(255) NOT NULL,
    PasswordHash VARCHAR2(255) NOT NULL,
    IsActive NUMBER(1) DEFAULT 1,
    OrganizationUnitId NUMBER NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50),
    AccessFailedCount NUMBER DEFAULT 0 NOT NULL,
    LockoutEnd TIMESTAMP NULL,
    LockoutEnabled NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT fk_appuser_orgunit FOREIGN KEY (OrganizationUnitId) REFERENCES ORGANIZATION_UNIT(Id)
);

CREATE TABLE ROLE (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code VARCHAR2(50) NOT NULL UNIQUE,
    Name VARCHAR2(255) NOT NULL,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50)
);

CREATE TABLE USER_ROLE (
    UserId VARCHAR2(36) NOT NULL,
    RoleId NUMBER NOT NULL,
    PRIMARY KEY (UserId, RoleId),
    CONSTRAINT fk_userrole_user FOREIGN KEY (UserId) REFERENCES APP_USER(Id) ON DELETE CASCADE,
    CONSTRAINT fk_userrole_role FOREIGN KEY (RoleId) REFERENCES ROLE(Id) ON DELETE CASCADE
);

CREATE TABLE PERMISSION (
    Id VARCHAR2(36) PRIMARY KEY,
    Code VARCHAR2(100) NOT NULL UNIQUE,
    Name VARCHAR2(200) NOT NULL,
    Description VARCHAR2(500) NULL,
    IsActive NUMBER(1) DEFAULT 1 NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CreatedBy VARCHAR2(36) NOT NULL,
    UpdatedAt TIMESTAMP NULL,
    UpdatedBy VARCHAR2(36) NULL
);

CREATE TABLE ROLE_PERMISSION (
    Id VARCHAR2(36) PRIMARY KEY,
    RoleId NUMBER NOT NULL,
    PermissionId VARCHAR2(36) NOT NULL,
    CONSTRAINT fk_rp_role FOREIGN KEY (RoleId) REFERENCES ROLE(Id) ON DELETE CASCADE,
    CONSTRAINT fk_rp_permission FOREIGN KEY (PermissionId) REFERENCES PERMISSION(Id) ON DELETE CASCADE
);

CREATE INDEX idx_rp_role_perm ON ROLE_PERMISSION(RoleId, PermissionId);

CREATE TABLE PERMISSION_DETAIL (
    Id VARCHAR2(36) PRIMARY KEY,
    PermissionId VARCHAR2(36) NOT NULL,
    ControllerName VARCHAR2(100) NOT NULL,
    ActionName VARCHAR2(100) NOT NULL,
    CONSTRAINT fk_pd_permission FOREIGN KEY (PermissionId) REFERENCES PERMISSION(Id) ON DELETE CASCADE
);

CREATE INDEX idx_pd_perm_ctrl ON PERMISSION_DETAIL(PermissionId, ControllerName);

CREATE TABLE USER_PERMISSION (
    UserId VARCHAR2(36) NOT NULL,
    PermissionId VARCHAR2(36) NOT NULL,
    PRIMARY KEY (UserId, PermissionId),
    CONSTRAINT fk_up_user FOREIGN KEY (UserId) REFERENCES APP_USER(Id) ON DELETE CASCADE,
    CONSTRAINT fk_up_permission FOREIGN KEY (PermissionId) REFERENCES PERMISSION(Id) ON DELETE CASCADE
);

CREATE TABLE SYSTEM_PARAM (
    ParamKey VARCHAR2(100) NOT NULL PRIMARY KEY,
    ParamValue VARCHAR2(4000) NOT NULL,
    Description VARCHAR2(1000) NULL,
    DataType VARCHAR2(50) DEFAULT 'String' NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP NULL
);

CREATE TABLE APP_MENU (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(100) NOT NULL,
    Url VARCHAR2(255) NULL,
    Icon VARCHAR2(50) NULL,
    ParentId NUMBER NULL,
    SortOrder NUMBER DEFAULT 0,
    IsActive NUMBER(1) DEFAULT 1,
    PermissionCode VARCHAR2(100) NULL,
    CONSTRAINT fk_menu_parent FOREIGN KEY (ParentId) REFERENCES APP_MENU(Id) ON DELETE CASCADE
);

CREATE TABLE USER_GROUP (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(100) NOT NULL,
    Description VARCHAR2(255) NULL,
    IsActive NUMBER(1) DEFAULT 1
);

CREATE TABLE USER_GROUP_MEMBER (
    UserGroupId NUMBER NOT NULL,
    UserId VARCHAR2(36) NOT NULL,
    PRIMARY KEY (UserGroupId, UserId),
    CONSTRAINT fk_ugm_group FOREIGN KEY (UserGroupId) REFERENCES USER_GROUP(Id) ON DELETE CASCADE,
    CONSTRAINT fk_ugm_user FOREIGN KEY (UserId) REFERENCES APP_USER(Id) ON DELETE CASCADE
);

CREATE TABLE USER_GROUP_ROLE (
    UserGroupId NUMBER NOT NULL,
    RoleId NUMBER NOT NULL,
    PRIMARY KEY (UserGroupId, RoleId),
    CONSTRAINT fk_ugr_group FOREIGN KEY (UserGroupId) REFERENCES USER_GROUP(Id) ON DELETE CASCADE,
    CONSTRAINT fk_ugr_role FOREIGN KEY (RoleId) REFERENCES ROLE(Id) ON DELETE CASCADE
);

CREATE TABLE USER_GROUP_PERMISSION (
    UserGroupId NUMBER NOT NULL,
    PermissionId VARCHAR2(36) NOT NULL,
    PRIMARY KEY (UserGroupId, PermissionId),
    CONSTRAINT fk_ugp_group FOREIGN KEY (UserGroupId) REFERENCES USER_GROUP(Id) ON DELETE CASCADE,
    CONSTRAINT fk_ugp_permission FOREIGN KEY (PermissionId) REFERENCES PERMISSION(Id) ON DELETE CASCADE
);

CREATE TABLE USER_UNIT_ROLE (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserId VARCHAR2(36) NOT NULL,
    UnitId NUMBER NOT NULL,
    RoleId NUMBER NOT NULL,
    CONSTRAINT fk_uur_user FOREIGN KEY (UserId) REFERENCES APP_USER(Id) ON DELETE CASCADE,
    CONSTRAINT fk_uur_unit FOREIGN KEY (UnitId) REFERENCES ORGANIZATION_UNIT(Id) ON DELETE CASCADE,
    CONSTRAINT fk_uur_role FOREIGN KEY (RoleId) REFERENCES ROLE(Id) ON DELETE CASCADE,
    CONSTRAINT uq_uur_user_unit_role UNIQUE (UserId, UnitId, RoleId)
);

CREATE TABLE UPLOAD_CONFIG (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ModuleCode VARCHAR2(50) NOT NULL UNIQUE,
    AllowedExtensions VARCHAR2(255) NOT NULL,
    MaxSizeMb NUMBER DEFAULT 10 NOT NULL,
    Description VARCHAR2(255) NULL
);
