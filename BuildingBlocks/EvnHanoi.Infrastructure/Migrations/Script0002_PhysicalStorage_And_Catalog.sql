CREATE TABLE PHYSICAL_FONDS (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code VARCHAR2(50) NOT NULL UNIQUE,
    Name VARCHAR2(255) NOT NULL,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50)
);

CREATE TABLE PHYSICAL_SHELF (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FondsId NUMBER NOT NULL,
    Code VARCHAR2(50) NOT NULL,
    Name VARCHAR2(255) NOT NULL,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50),
    CONSTRAINT fk_phys_shelf_fonds FOREIGN KEY (FondsId) REFERENCES PHYSICAL_FONDS(Id)
);

CREATE TABLE PHYSICAL_FLOOR (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ShelfId NUMBER NOT NULL,
    Code VARCHAR2(50) NOT NULL,
    Name VARCHAR2(255) NOT NULL,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50),
    CONSTRAINT fk_phys_floor_shelf FOREIGN KEY (ShelfId) REFERENCES PHYSICAL_SHELF(Id)
);

CREATE TABLE PHYSICAL_BOX (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FloorId NUMBER NOT NULL,
    Code VARCHAR2(50) NOT NULL,
    Name VARCHAR2(255) NOT NULL,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50),
    CONSTRAINT fk_phys_box_floor FOREIGN KEY (FloorId) REFERENCES PHYSICAL_FLOOR(Id)
);

CREATE TABLE CATALOG (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Code VARCHAR2(50) NOT NULL UNIQUE,
    Name VARCHAR2(255) NOT NULL,
    CatalogType VARCHAR2(50) DEFAULT 'System' NOT NULL,
    ParentId NUMBER NULL,
    Description VARCHAR2(1000) NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CreatedBy VARCHAR2(50),
    UpdatedAt TIMESTAMP,
    UpdatedBy VARCHAR2(50),
    CONSTRAINT fk_catalog_parent FOREIGN KEY (ParentId) REFERENCES CATALOG(Id)
);
