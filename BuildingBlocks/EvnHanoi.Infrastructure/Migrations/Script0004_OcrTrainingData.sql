-- Script0004: Tạo bảng OCR_TRAINING_DATA để quản lý dữ liệu huấn luyện AI-OCR
-- Ngày tạo: 2026-05-29

CREATE TABLE OCR_TRAINING_DATA (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILE_NAME           VARCHAR2(500)  NOT NULL,
    FILE_PATH           VARCHAR2(2000) NOT NULL,
    BUCKET_NAME         VARCHAR2(255)  NOT NULL,
    CONTENT_TYPE        VARCHAR2(100)  NOT NULL,
    FILE_SIZE           NUMBER         NOT NULL,
    DOCUMENT_TYPE       VARCHAR2(100),
    LABEL_TEXT          CLOB,
    QUALITY_SCORE       NUMBER(5,2),
    TRAINING_STATUS     VARCHAR2(50)   DEFAULT 'Pending' NOT NULL,
    IS_VERIFIED         NUMBER(1)      DEFAULT 0,
    VERIFIED_BY         VARCHAR2(255),
    VERIFIED_AT         TIMESTAMP,
    NOTES               VARCHAR2(2000),
    UPLOADED_AT         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPLOADED_BY         VARCHAR2(255)  NOT NULL,
    CREATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

COMMENT ON TABLE OCR_TRAINING_DATA IS 'Bảng lưu trữ dữ liệu huấn luyện cho mô hình AI-OCR nhận dạng văn bản hồ sơ kỹ thuật';
COMMENT ON COLUMN OCR_TRAINING_DATA.TRAINING_STATUS IS 'Trạng thái: Pending, Labeled, Verified, Rejected';
COMMENT ON COLUMN OCR_TRAINING_DATA.QUALITY_SCORE IS 'Điểm chất lượng ảnh (0.00-100.00)';
COMMENT ON COLUMN OCR_TRAINING_DATA.IS_VERIFIED IS '1=Đã xác nhận; 0=Chưa xác nhận';
