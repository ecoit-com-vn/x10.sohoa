ALTER TABLE CATALOG ADD UnitId NUMBER NULL;

-- Tạo bảng VIRTUAL_FOLDERS
CREATE TABLE VIRTUAL_FOLDERS (
    Id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(255) NOT NULL,
    ParentId NUMBER NULL,
    UnitId NUMBER NULL,
    CreatedBy VARCHAR2(100) NULL,
    CreatedDate TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_virtual_folder_parent FOREIGN KEY (ParentId) REFERENCES VIRTUAL_FOLDERS(Id) ON DELETE CASCADE
);

-- Tạo bảng FOLDER_DOCUMENTS
CREATE TABLE FOLDER_DOCUMENTS (
    FolderId NUMBER NOT NULL,
    DocumentId NUMBER NOT NULL,
    PRIMARY KEY (FolderId, DocumentId),
    CONSTRAINT fk_folder_doc_folder FOREIGN KEY (FolderId) REFERENCES VIRTUAL_FOLDERS(Id) ON DELETE CASCADE,
    CONSTRAINT fk_folder_doc_doc FOREIGN KEY (DocumentId) REFERENCES FILE_ATTACHMENT(ID) ON DELETE CASCADE
);
