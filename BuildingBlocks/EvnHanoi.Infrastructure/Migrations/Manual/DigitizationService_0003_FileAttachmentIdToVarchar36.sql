-- NỘI DUNG: 0001_Schema.sql tạo FILE_ATTACHMENT.ID = NUMBER GENERATED BY DEFAULT AS IDENTITY
-- và FOLDER_DOCUMENTS.DOCUMENTID = NUMBER, nhưng toàn bộ code C# coi khoá này là Guid
-- (FileAttachment.Id, AddDocumentToFolderAsync(long, Guid), OcrTaskMessage.FileId) nên mọi
-- INSERT đều chết ORA-01722. Script đổi 2 cột sang VARCHAR2(36) theo quy ước khoá chính của
-- project (BACKEND_GUIDELINES.md §2) và dựng lại FK_FOLDER_DOC_DOC. Idempotent: chạy lại
-- trên DB đã đổi kiểu thì không làm gì.
