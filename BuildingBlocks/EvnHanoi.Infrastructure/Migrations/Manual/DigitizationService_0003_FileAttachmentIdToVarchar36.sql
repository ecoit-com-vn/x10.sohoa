SET SERVEROUTPUT ON

BEGIN
    -- 1. Bỏ FK trước khi đổi kiểu 2 cột hai đầu quan hệ.
    FOR c IN (
        SELECT 1
        FROM user_tab_cols
        WHERE table_name = 'FOLDER_DOCUMENTS'
          AND column_name = 'DOCUMENTID'
          AND data_type = 'NUMBER'
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE FOLDER_DOCUMENTS DROP CONSTRAINT FK_FOLDER_DOC_DOC';
            DBMS_OUTPUT.PUT_LINE('Đã bỏ FK_FOLDER_DOC_DOC');
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -2443 THEN RAISE; END IF;  -- -2443: constraint không tồn tại
                DBMS_OUTPUT.PUT_LINE('FK_FOLDER_DOC_DOC không tồn tại, bỏ qua');
        END;
    END LOOP;

    -- 2. Cột IDENTITY không đổi được kiểu khi còn thuộc tính identity.
    FOR c IN (
        SELECT 1
        FROM user_tab_cols
        WHERE table_name = 'FILE_ATTACHMENT'
          AND column_name = 'ID'
          AND identity_column = 'YES'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE FILE_ATTACHMENT MODIFY ID DROP IDENTITY';
        DBMS_OUTPUT.PUT_LINE('Đã bỏ IDENTITY của FILE_ATTACHMENT.ID');
    END LOOP;

    -- 3. Đổi kiểu FILE_ATTACHMENT.ID -> VARCHAR2(36).
    FOR c IN (
        SELECT 1
        FROM user_tab_cols
        WHERE table_name = 'FILE_ATTACHMENT'
          AND column_name = 'ID'
          AND data_type = 'NUMBER'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE FILE_ATTACHMENT MODIFY (ID VARCHAR2(36))';
        DBMS_OUTPUT.PUT_LINE('FILE_ATTACHMENT.ID -> VARCHAR2(36)');
    END LOOP;

    -- 4. Đổi kiểu FOLDER_DOCUMENTS.DOCUMENTID -> VARCHAR2(36).
    FOR c IN (
        SELECT 1
        FROM user_tab_cols
        WHERE table_name = 'FOLDER_DOCUMENTS'
          AND column_name = 'DOCUMENTID'
          AND data_type = 'NUMBER'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE FOLDER_DOCUMENTS MODIFY (DOCUMENTID VARCHAR2(36))';
        DBMS_OUTPUT.PUT_LINE('FOLDER_DOCUMENTS.DOCUMENTID -> VARCHAR2(36)');
    END LOOP;

    -- 5. Dựng lại FK nếu đang thiếu.
    FOR c IN (
        SELECT 1
        FROM user_tab_cols f
        WHERE f.table_name = 'FOLDER_DOCUMENTS'
          AND f.column_name = 'DOCUMENTID'
          AND f.data_type = 'VARCHAR2'
          AND NOT EXISTS (
              SELECT 1 FROM user_constraints
              WHERE constraint_name = 'FK_FOLDER_DOC_DOC'
                AND table_name = 'FOLDER_DOCUMENTS'
          )
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE FOLDER_DOCUMENTS ADD CONSTRAINT FK_FOLDER_DOC_DOC '
                       || 'FOREIGN KEY (DOCUMENTID) REFERENCES FILE_ATTACHMENT(ID) ON DELETE CASCADE';
        DBMS_OUTPUT.PUT_LINE('Đã dựng lại FK_FOLDER_DOC_DOC');
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('Hoàn tất.');
END;
